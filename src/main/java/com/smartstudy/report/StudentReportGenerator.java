package com.smartstudy.report;

import com.smartstudy.model.*;
import com.smartstudy.service.*;

import java.time.LocalDate;
import java.time.format.DateTimeFormatter;
import java.util.List;

/**
 * Concrete report generator for student weekly reports.
 * Extends abstract ReportGenerator.
 */
public class StudentReportGenerator extends ReportGenerator {

    private final String studentName;
    private final TaskService taskService;
    private final ProgressService progressService;
    private final SubjectService subjectService;
    private final RecommendationService recommendationService;

    public StudentReportGenerator(int studentId, String studentName) {
        super(studentId);
        this.studentName = studentName;
        this.taskService = new TaskService();
        this.progressService = new ProgressService();
        this.subjectService = new SubjectService();
        this.recommendationService = new RecommendationService();
    }

    @Override
    public String generateContent() {
        StringBuilder sb = new StringBuilder();
        String date = LocalDate.now().format(DateTimeFormatter.ofPattern("yyyy-MM-dd"));

        sb.append("============================================\n");
        sb.append("       SMARTSTUDY WEEKLY REPORT\n");
        sb.append("============================================\n");
        sb.append("Student: ").append(studentName).append("\n");
        sb.append("Date: ").append(date).append("\n");
        sb.append("============================================\n\n");

        // Overall Progress
        double overallProgress = progressService.getOverallProgress(studentId);
        double totalHours = progressService.getTotalStudyHours(studentId);
        sb.append("--- OVERALL SUMMARY ---\n");
        sb.append("Overall Progress: ").append(String.format("%.1f%%", overallProgress)).append("\n");
        sb.append("Total Study Hours: ").append(String.format("%.1f", totalHours)).append(" hours\n");
        sb.append("Completed Tasks: ").append(taskService.getCompletedCount(studentId)).append("\n");
        sb.append("Pending Tasks: ").append(taskService.getPendingCount(studentId)).append("\n\n");

        // Subject-wise Progress
        sb.append("--- SUBJECT-WISE PROGRESS ---\n");
        List<Subject> subjects = subjectService.getSubjectsByStudentId(studentId);
        for (Subject subject : subjects) {
            double subProgress = progressService.getSubjectProgress(subject.getId());
            double subHours = progressService.getSubjectStudyHours(subject.getId());
            sb.append(String.format("  %-35s  Progress: %5.1f%%  Study: %.1f hrs\n",
                subject.getName() + " (" + subject.getCourseCode() + ")",
                subProgress, subHours));
        }
        sb.append("\n");

        // Pending Tasks
        sb.append("--- PENDING TASKS ---\n");
        List<Task> pending = taskService.getPendingTasks(studentId);
        if (pending.isEmpty()) {
            sb.append("  No pending tasks. Great job!\n");
        } else {
            for (Task task : pending) {
                sb.append("  [").append(task.getStatus()).append("] ")
                  .append(task.getTitle());
                if (task.getDeadline() != null) {
                    sb.append(" (Due: ").append(task.getDeadline()).append(")");
                }
                sb.append("\n");
            }
        }
        sb.append("\n");

        // Recommendations
        sb.append("--- RECOMMENDATIONS ---\n");
        List<String> recommendations = recommendationService.getRecommendations(studentId);
        for (String rec : recommendations) {
            sb.append("  ").append(rec).append("\n");
        }
        sb.append("\n");

        sb.append("============================================\n");
        sb.append("  Report generated by SmartStudy v1.0\n");
        sb.append("============================================\n");

        return sb.toString();
    }

    @Override
    public String getFileName() {
        String date = LocalDate.now().format(DateTimeFormatter.ofPattern("yyyy_MM_dd"));
        return "weekly_report_" + date + ".txt";
    }
}
